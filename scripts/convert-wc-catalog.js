// Converts a WooCommerce product export (CSV, Spanish headers) into SQL that loads the catalog.
// Only simple products with a price and a rental category come in: variations, Catering, rows
// without a price and a repeated name are skipped and listed. Unpublished products are inactive. The export has no stock, so every product starts at 0 units, to fill in Productos.
// Idempotent like the seed: a product whose name already exists (any case) is skipped.
// Rows get `created_by = 'system'` and write no events row.
// Usage: node scripts/convert-wc-catalog.js <export.csv> <products-import.sql>
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const USAGE = 'Usage: node scripts/convert-wc-catalog.js <export.csv> <products-import.sql>';

// A product in several categories takes the first one listed. Catering is food, not rental.
const CATEGORIES = {
	'Sillas y Mesas': 'CHAIRS_TABLES',
	'Manteles y Ruches': 'LINENS',
	Cristalería: 'GLASSWARE',
	Cubiertos: 'CUTLERY',
	'Platos y Vajilla': 'TABLEWARE',
	'Samovares y bandejas': 'CHAFERS_TRAYS',
	'Elementos de Decoración': 'DECOR'
};

/** RFC 4180 rows: quoted fields may hold commas, newlines and doubled quotes. */
export function parseCsv(text) {
	const rows = [[]];
	for (const [, field, separator] of text.matchAll(/("(?:[^"]|"")*"|[^,\r\n]*)(,|\r?\n|$)/g)) {
		rows.at(-1).push(field.startsWith('"') ? field.slice(1, -1).replaceAll('""', '"') : field);
		if ('' === separator) {
			break;
		}
		if (',' !== separator) {
			rows.push([]);
		}
	}
	return rows.filter((row) => row.some(Boolean));
}

/** WooCommerce's HTML description as plain text; it writes some newlines as a literal `\n`. */
export function toPlainText(html) {
	const text = html
		.replaceAll('\\n', '\n')
		.replace(/<[^>]*>/g, '')
		.replaceAll('&nbsp;', ' ')
		.split('\n')
		.map((line) => line.replace(/\s+/g, ' ').trim())
		.join('\n')
		.replace(/\n{3,}/g, '\n\n')
		.trim();
	return text || null;
}

/** Why `record` stays out of the catalog, or null when it comes in. */
function skipReason(record, product, names) {
	if ('simple' !== record['Tipo']) {
		return record['Tipo'];
	}
	if (!product.category) {
		return `category «${record['Categorías']}»`;
	}
	if (!Number.isInteger(product.rentalPrice) || product.rentalPrice <= 0) {
		return `price «${record['Precio normal']}»`;
	}
	return names.has(product.name.toLowerCase()) ? 'repeated name' : null;
}

/**
 * The catalog rows from the export's records (header → value), and the skipped ones with why.
 * @returns {{ products: object[], skipped: string[] }}
 */
export function toProducts(records) {
	const products = [];
	const skipped = [];
	const names = new Set();
	for (const record of records) {
		const product = {
			name: record['Nombre'].trim(),
			category: CATEGORIES[record['Categorías'].split(',')[0].trim()],
			description: toPlainText(record['Descripción corta']) ?? toPlainText(record['Descripción']),
			rentalPrice: Number(record['Precio normal']),
			active: '1' === record['Publicado'] ? 1 : 0
		};
		const reason = skipReason(record, product, names);
		if (reason) {
			skipped.push(`${record['ID']} ${product.name}: ${reason}`);
			continue;
		}
		names.add(product.name.toLowerCase());
		products.push(product);
	}
	return { products, skipped };
}

function quote(value) {
	return null === value ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`;
}

/** One INSERT for every product, skipping a name that already exists in any case. */
export function toSql(products) {
	const values = products
		.map(
			(product) =>
				`\t(${[product.name, product.category, product.description].map(quote).join(', ')}, ${product.rentalPrice}, ${product.active})`
		)
		.join(',\n');
	return `-- Generated by scripts/convert-wc-catalog.js from a WooCommerce product export.
INSERT INTO products (name, category, description, rental_price, total_quantity, active, created_at, created_by, updated_at, updated_by)
SELECT column1, column2, column3, column4, 0, column5, unixepoch(), 'system', unixepoch(), 'system'
FROM (VALUES
${values}
) AS export
WHERE NOT EXISTS (SELECT 1 FROM products WHERE products.name = export.column1 COLLATE NOCASE);
`;
}

function main() {
	const [input, output] = process.argv.slice(2);
	if (!input || !output) {
		console.error(USAGE);
		process.exit(2);
	}
	const [header, ...rows] = parseCsv(readFileSync(input, 'utf8').replace(/^\uFEFF/, ''));
	const records = rows.map((row) =>
		Object.fromEntries(header.map((key, i) => [key, row[i] ?? '']))
	);
	const { products, skipped } = toProducts(records);
	writeFileSync(output, toSql(products));

	const inactive = products.filter((product) => !product.active).length;
	console.log(`Wrote ${products.length} products to ${output} (${inactive} inactive).`);
	console.log(`Skipped ${skipped.length}:\n${skipped.map((line) => `  ${line}`).join('\n')}`);
	console.log(
		`\nTo import into development:\n  npx wrangler d1 execute consueloc-erp-db --local --file ${output}`
	);
	console.log(
		`To import into production:\n  npx wrangler d1 execute consueloc-erp-db --remote --file ${output}`
	);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	main();
}
